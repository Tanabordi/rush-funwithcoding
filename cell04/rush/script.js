//
//  ต้องโหลด jQuery ก่อนเสมอ เพราะไฟล์นี้ใช้ตัวแปร $
//
//  ทำงานคู่กับ style.css :
//    .fade-element          = สถานะเริ่มต้น (จาง + ถูกดันลง 40px)
//    .fade-element.visible  = สถานะปลายทาง (ทึบ + กลับตำแหน่งเดิม)
//    JavaScript มีหน้าที่แค่ "เพิ่มคลาส" ส่วนการเคลื่อนไหวจริง CSS จัดการเอง
// ============================================================================

// $(document).ready(...) = รอให้เบราว์เซอร์อ่าน HTML ครบทั้งหน้าก่อน
// จึงค่อยรันโค้ดข้างใน ป้องกันการไปหาองค์ประกอบที่ยังไม่ถูกสร้าง
$(document).ready(function() {
    // ใส่คลาส .fade-element ให้ทุก .container ที่อยู่ภายใน <section> ด้วย JavaScript
    // ข้อดี : ไม่ต้องไปเขียนคลาสนี้ซ้ำ ๆ ในไฟล์ HTML ทั้งสองหน้า
    //         ถ้าเพิ่ม <section> ใหม่ในอนาคต เอฟเฟกต์จะทำงานให้อัตโนมัติ
    // ผลทันที : CSS ทำให้ทุกอันจางหายและถูกดันลงไป 40px
    $('section .container').addClass('fade-element');

    // ฟังก์ชันตรวจว่า "องค์ประกอบไหนเลื่อนเข้ามาในหน้าจอแล้วบ้าง"
    function checkScroll() {
        // ความสูงของพื้นที่ที่มองเห็นบนหน้าจอ (พิกเซล)
        var windowHeight = $(window).height();
        // ระยะที่ผู้ใช้เลื่อนลงมาแล้วจากบนสุดของหน้า (พิกเซล)
        var scrollPos = $(window).scrollTop();

        // วนซ้ำทีละตัวกับทุกองค์ประกอบที่มีคลาส .fade-element
        // ภายในฟังก์ชันนี้ $(this) หมายถึงตัวที่กำลังวนอยู่
        $('.fade-element').each(function() {
            // ระยะจากขอบบนสุดของ "ทั้งหน้าเอกสาร" จนถึงองค์ประกอบนี้
            // (ไม่ใช่ระยะจากขอบบนของหน้าจอ)
            var elementPos = $(this).offset().top;
            // เงื่อนไขหลัก :
            //   ซ้าย  (scrollPos + windowHeight) = ตำแหน่งขอบล่างของหน้าจอ ในระบบพิกัดของเอกสาร
            //   ขวา   (elementPos + 100)         = ตำแหน่งขององค์ประกอบ บวกระยะเผื่อ 100px
            // เมื่อขอบล่างจอเลื่อนผ่านจุดนั้น = องค์ประกอบโผล่เข้ามาในจอลึกพอแล้ว
            // เลข +100 คือระยะหน่วง ทำให้เอฟเฟกต์ไม่เริ่มทันทีที่เห็นขอบบนเพียงนิดเดียว
            if (scrollPos + windowHeight > elementPos + 100) {
                // จุดเชื่อมต่อกับ CSS : พอเพิ่มคลาส .visible
                // กฎ .fade-element.visible ใน style.css จะทำงาน แล้ว transition
                // จะค่อย ๆ เปลี่ยน opacity จาก 0 เป็น 1 และเลื่อนขึ้น 40px ภายใน 0.8 วินาที
                // หมายเหตุ : ไม่มีการลบคลาสนี้ออก จึงเป็นเอฟเฟกต์แบบ "ปรากฏแล้วปรากฏเลย"
                $(this).addClass('visible');
            }
        });
    }

    // ผูกฟังก์ชันไว้กับเหตุการณ์เลื่อนหน้าจอ - ผู้ใช้เลื่อนทีไร ฟังก์ชันถูกเรียกทุกครั้ง
    $(window).on('scroll', checkScroll);
    // เรียกหนึ่งครั้งทันทีตอนโหลดหน้าเสร็จ (สำคัญมาก)
    // เพื่อให้เนื้อหาที่อยู่ในจอตั้งแต่แรกปรากฏขึ้นมาเลย
    // ถ้าไม่มีบรรทัดนี้ ผู้ใช้จะเปิดหน้ามาเจอหน้าจอว่างจนกว่าจะเลื่อน
    checkScroll();
});
